const delay = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

export async function fetchMockRevisedAnswer(
  prompt: string,
  findings: EvaluatorResult[]
): Promise<string> {
  await delay(1200);

  const weaknesses = findings
    .flatMap((r) => r.weaknesses.slice(0, 1))
    .filter(Boolean);

  const verifyItems = findings
    .flatMap((r) => r.verifyBeforeUse.slice(0, 1))
    .filter(Boolean);

  return `**Revised response** — incorporating evaluator feedback

**What changed from the original**
The evaluators flagged ${weaknesses.length > 0 ? weaknesses.slice(0, 2).join("; ").toLowerCase() : "missing verifiability and overconfident framing"}. This revision addresses those gaps directly.

**Refined answer**

${prompt.trim().slice(0, 60).replace(/\?$/, "")} requires a structured approach that separates what is well-supported from what still needs verification.

**Strengthened reasoning**
- The core recommendation stands, but assumptions are now made explicit rather than left implicit
- Claims that depend on your specific context have been flagged as such
- Logical steps between premises and conclusions are spelled out rather than assumed

**Confidence calibration**
The original answer presented a single confident path. In practice, the right answer here depends on at least two variables that only you can verify: your specific constraints and current ground truth.

**What to verify before acting**
${verifyItems.length > 0 ? verifyItems.map((v) => `- ${v}`).join("\n") : "- Confirm the assumptions match your actual situation\n- Cross-check any domain-specific claims with a primary source"}

*This revision was generated by incorporating findings from ${findings.map((f) => f.name).join(", ")}.*`;
}

export async function fetchMockAlternateAnswer(prompt: string): Promise<{ answer: string; comparison: string }> {
  await delay(1200);

  const answer = `**Alternative framing — decision criteria first**

Rather than a step-by-step plan, here is a **criteria-based decision guide** for: *${prompt.trim().slice(0, 70)}${prompt.length > 70 ? "…" : ""}*

**Start by asking: what does "good enough" look like?**
Before generating or evaluating any answer, define your acceptance threshold:
- Is this for a low-stakes internal note, or an external deliverable?
- Can you afford to be wrong, or is accuracy critical?
- Will you act immediately on this, or is it informing a longer process?

**Match your evaluation depth to the stakes**

| Stakes level | Recommended approach |
|---|---|
| Low — exploratory, internal | Take the first answer, skim it, act |
| Medium — shared with stakeholders | Run 1–2 evaluators; fix flagged gaps |
| High — public, regulated, or irreversible | Run all relevant evaluators; verify externally |

**Why this framing differs**
The original answer told you *what to do*. This version tells you *how to decide what to do* — which is more durable across different prompts and contexts.

**Next step**
Pick your stakes level above, then either keep the original answer, revise it with evaluator findings, or use a specialist (legal, medical, financial) for high-stakes cases.`;

  const comparison = `The original took an execution-first approach — prescribing concrete steps. This alternate reframes the problem as a decision under uncertainty: it helps you determine *how much* to verify before acting, rather than assuming a single right answer applies universally. Better suited for ambiguous, high-variance situations.`;

  return { answer, comparison };
}


